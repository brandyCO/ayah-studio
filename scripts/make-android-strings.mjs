// Writes the Android app-shortcut labels (long-press the app icon) in every interface language:
// android/app/src/main/res/values-{qualifier}/strings.xml from the `extra` module of src/i18n/locales/{lang}.json.
// Android shows them in the phone's language. Arabic (values-ar) is kept as written by hand.
// Run after the translations change: node scripts/make-android-strings.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = path.join(root, 'src/i18n/locales');
// Android's resource folder for each language (Indonesian keeps its old code `in`; Sorani needs the BCP 47 form).
const QUAL = { id: 'in', ckb: 'b+ckb' };
const KEYS = [['sc_read', 'sc.read'], ['sc_read_long', 'sc.readLong'], ['sc_goals', 'sc.goals'], ['sc_goals_long', 'sc.goalsLong'],
  ['sc_search', 'sc.search'], ['sc_search_long', 'sc.searchLong'], ['sc_reels', 'sc.reels'], ['sc_reels_long', 'sc.reelsLong']];
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/'/g, "\\'").replace(/"/g, '\\"').replace(/^@/, '\\@').replace(/^\?/, '\\?');

let n = 0;
for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.json'))) {
  const id = f.slice(0, -5);
  const extra = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')).extra ?? {};
  const rows = KEYS.filter(([, k]) => extra[k]).map(([name, k]) => `    <string name="${name}">${esc(extra[k])}</string>`);
  if (rows.length < KEYS.length) { console.log(`${id}: shortcuts not translated yet, skipped`); continue; }
  const out = path.join(root, 'android/app/src/main/res', `values-${QUAL[id] ?? id}`);
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, 'strings.xml'), `<?xml version='1.0' encoding='utf-8'?>\n<!-- Generated by scripts/make-android-strings.mjs -->\n<resources>\n${rows.join('\n')}\n</resources>\n`);
  n++;
}
console.log(`${n} languages written`);
