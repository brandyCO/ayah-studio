// Writes the iPhone permission questions in every interface language: ios/App/App/{lang}.lproj/InfoPlist.strings
// from scripts/i18n/ios-infoplist.json, and lists the languages in Info.plist's CFBundleLocalizations (so iOS shows
// the app's language in Settings). Run: node scripts/make-ios-strings.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const src = JSON.parse(readFileSync('scripts/i18n/ios-infoplist.json', 'utf8'));
const KEYS = { photos: 'NSPhotoLibraryAddUsageDescription', mic: 'NSMicrophoneUsageDescription', speech: 'NSSpeechRecognitionUsageDescription', location: 'NSLocationWhenInUseUsageDescription' };
const LPROJ = { zh: 'zh-Hans' };
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
const langs = Object.keys(src).filter((k) => !k.startsWith('_'));
for (const lang of langs) {
  const dir = `ios/App/App/${LPROJ[lang] ?? lang}.lproj`;
  mkdirSync(dir, { recursive: true });
  const t = src[lang];
  for (const k of Object.keys(KEYS)) if (!t[k]) throw new Error(`${lang}: ${k} missing`);
  writeFileSync(`${dir}/InfoPlist.strings`, `/* Generated by scripts/make-ios-strings.mjs */\n"CFBundleDisplayName" = "Ayah Studio";\n` +
    Object.entries(KEYS).map(([k, key]) => `"${key}" = "${esc(t[k])}";`).join('\n') + '\n');
}
const plist = 'ios/App/App/Info.plist';
const list = langs.map((l) => `\t\t<string>${LPROJ[l] ?? l}</string>`).join('\n');
const text = readFileSync(plist, 'utf8').replace(/(<key>CFBundleLocalizations<\/key>\s*)<array(?:\/>|>[\s\S]*?<\/array>)/, `$1<array>\n${list}\n\t</array>`);
writeFileSync(plist, text);
console.log(`${langs.length} languages`);
