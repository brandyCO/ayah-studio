// One-off: fetch the curated translations of the meaning into public/data/tr/ (docs/grow.md, G1).
// Run with `node scripts/fetch-translations.mjs`, then commit the output.
//
// Source: the Tanzil translation collection via api.alquran.cloud (the same route as the bundled
// Saheeh International, en-sahih.json). Tanzil offers these translations for non-commercial use;
// each translation's rights stay with its translator / publisher (see public/data/tr/README.md).
// Text is stored exactly as published: nothing is trimmed, re-typed or "cleaned".
import { readFile, writeFile } from 'node:fs/promises';

const OUT = new URL('../public/data/tr/', import.meta.url);
const meta = JSON.parse(await readFile(new URL('../public/data/meta.json', import.meta.url), 'utf8'));

// id (alquran.cloud edition), language (BCP 47), language name (own + English), translator as credited.
export const EDITIONS = [
  ['en.pickthall', 'en', 'English', 'English', 'Mohammed Marmaduke William Pickthall'],
  ['en.yusufali', 'en', 'English', 'English', 'Abdullah Yusuf Ali'],
  ['ur.jalandhry', 'ur', 'اردو', 'Urdu', 'Fateh Muhammad Jalandhry'],
  ['ur.junagarhi', 'ur', 'اردو', 'Urdu', 'Muhammad Junagarhi'],
  ['id.indonesian', 'id', 'Bahasa Indonesia', 'Indonesian', 'Kementerian Agama Republik Indonesia'],
  ['tr.diyanet', 'tr', 'Türkçe', 'Turkish', 'Diyanet İşleri'],
  ['fr.hamidullah', 'fr', 'Français', 'French', 'Muhammad Hamidullah'],
  ['ms.basmeih', 'ms', 'Bahasa Melayu', 'Malay', 'Abdullah Muhammad Basmeih'],
  ['bn.bengali', 'bn', 'বাংলা', 'Bengali', 'Muhiuddin Khan'],
  ['de.bubenheim', 'de', 'Deutsch', 'German', 'A. S. F. Bubenheim & N. Elyas'],
  ['es.cortes', 'es', 'Español', 'Spanish', 'Julio Cortés'],
  ['ru.kuliev', 'ru', 'Русский', 'Russian', 'Elmir Kuliev'],
  ['hi.hindi', 'hi', 'हिन्दी', 'Hindi', 'Suhel Farooq Khan & Saifur Rahman Nadwi'],
  ['sw.barwani', 'sw', 'Kiswahili', 'Swahili', 'Ali Muhsin Al-Barwani'],
];

function assert(cond, msg) {
  if (!cond) throw new Error(`Verification failed: ${msg}`);
}

const list = [{
  id: 'en.sahih', lang: 'en', langName: 'English', langEn: 'English', translator: 'Saheeh International',
  dir: 'ltr', file: '../en-sahih.json', bytes: (await readFile(new URL('../public/data/en-sahih.json', import.meta.url))).length,
}];
for (const [id, lang, langName, langEn, translator] of EDITIONS) {
  const res = await fetch(`https://api.alquran.cloud/v1/quran/${id}`);
  if (!res.ok) throw new Error(`${id} → HTTP ${res.status}`);
  const d = (await res.json()).data;
  assert(d.edition.identifier === id, `${id} edition`);
  assert(d.surahs.length === 114, `${id}: 114 surahs`);
  let n = 0;
  const surahs = d.surahs.map((s, i) => {
    assert(s.number === i + 1 && s.ayahs.length === meta[i].ayahs, `${id}: surah ${i + 1} has ${meta[i].ayahs} ayat`);
    return s.ayahs.map((a, j) => {
      assert(a.numberInSurah === j + 1 && typeof a.text === 'string' && a.text.trim().length > 0, `${id}: ${i + 1}:${j + 1} non-empty`);
      n++;
      return a.text;
    });
  });
  assert(n === 6236, `${id}: 6236 ayat`);
  const dir = d.edition.direction === 'rtl' ? 'rtl' : 'ltr';
  const body = JSON.stringify({
    source: `${translator} (${langEn}), Tanzil translation collection via api.alquran.cloud (edition ${id}). Unmodified; non-commercial use.`,
    id, lang, dir, translator, surahs,
  }) + '\n';
  await writeFile(new URL(`${id}.json`, OUT), body);
  list.push({ id, lang, langName, langEn, translator, dir, file: `${id}.json`, bytes: Buffer.byteLength(body) });
  console.log(`OK ${id}: 6236 ayat, ${(Buffer.byteLength(body) / 1024).toFixed(0)} KB`);
}
await writeFile(new URL('index.json', OUT), JSON.stringify(list, null, 1) + '\n');
// The app's copy of the list (src/data/translationList.ts), so the picker and reel credits need no fetch.
const ts = `// Generated by scripts/fetch-translations.mjs — do not edit by hand.
export interface TranslationInfo { id: string; lang: string; langName: string; langEn: string; translator: string; dir: 'ltr' | 'rtl'; bytes: number }
export const TRANSLATIONS: TranslationInfo[] = ${JSON.stringify(list.map(({ file, ...x }) => x), null, 1)};
`;
await writeFile(new URL('../src/data/translationList.ts', import.meta.url), ts);
console.log(`Wrote ${list.length} translations to public/data/tr/`);
